import nibabel as nib
import numpy as np
import pandas as pd
from pathlib import Path
from tqdm import tqdm

class Voxel:
    def __init__(self, mask_path: str):
        self.mask_path = mask_path
        self.mask_img = None
        self.mask_data = None

    def load(self):
        self.mask_img = nib.load(self.mask_path)
        self.mask_data = self.mask_img.get_fdata()
        return self.mask_data

    def voxel_sizes(self):
        if self.mask_img is None:
            self.load()
        return np.abs(self.mask_img.header.get_zooms())

    def voxel_volume(self):
        return np.prod(self.voxel_sizes())

    def label_volumes(self):
        """Return {label: volume_mm3}"""
        if self.mask_data is None:
            self.load()
        voxel_vol = self.voxel_volume()
        labels = np.unique(self.mask_data)
        labels = labels[labels > 0]
        return {int(label): np.sum(self.mask_data == label) * voxel_vol for label in labels}

# ----------- AUTOMATION SECTION -----------
root_dir = Path("/Volumes/T9/Imaging")  # top folder with all patients
nii_files = sorted(root_dir.rglob("t1_seg_mask.nii.gz"))  # sorted for consistent order

print(f"Found {len(nii_files)} segmentation files!")

records = []

for f in tqdm(nii_files, desc="Processing segmentations"):
    try:
        # Adjust folder indices based on your directory depth
        patient_id = f.parts[-6]
        week = f.parts[-5]

        v = Voxel(str(f))
        label_vols = v.label_volumes()

        # convert mm³ to mL and flatten into a single record
        record = {"Patient": patient_id, "Week": week}
        for label, volume in label_vols.items():
            record[f"Label_{label} (mL)"] = volume / 1000
        records.append(record)

    except Exception as e:
        print(f"⚠️ Error processing {f}: {e}")

# Create DataFrame and fill missing labels with 0
df = pd.DataFrame(records).sort_values(by=["Patient", "Week"]).fillna(0)

# Save results
df.to_xlsx("segmentation_volumes_by_patient.xlsx", index=False)
print("\n✅ Saved to segmentation_volumes_by_patient.xlsx")
